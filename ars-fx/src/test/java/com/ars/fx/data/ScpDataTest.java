package com.ars.fx.data;

import static org.junit.jupiter.api.Assertions.*;

import java.util.List;
import org.junit.jupiter.api.Test;

class ScpDataTest {
    static final String FILE = "!!Order,1,1\n#\n# Super Check Partial\n# Release 2026.11.04\n# Generated by bb-scp\n#\n"
            + "K1ABC\nK1ABD\nK1ABCD\nW1AW\nW1AWX\nN1MM\nVE3XYZ\nDL1ABC\nK1BAC\nk1abc\n\nnot a call!\nABCDEF\n";

    @Test void parsesTheFileAndSkipsCommentsHeadersAndRubbish() {
        ScpData d = ScpData.parse(FILE);
        assertEquals(9, d.size(), "unique upper-case calls with a digit; the duplicate k1abc, comments, !!Order, junk and a call with no digit are skipped");
        assertEquals("2026.11.04", d.release());
        assertTrue(d.contains("k1abd"), "lookup ignores case");
        assertFalse(d.contains("W9ZZZ"));
        assertTrue(ScpData.parse(null).isEmpty());
        assertTrue(ScpData.parse("").isEmpty());
        assertEquals("", ScpData.parse("K1ABC\n").release());
    }

    @Test void partialFindsCallsContainingWhatIsTypedPrefixMatchesFirst() {
        ScpData d = ScpData.parse(FILE);
        ScpData.Result r = d.partial("1AB", 10);
        assertEquals(List.of("DL1ABC", "K1ABC", "K1ABCD", "K1ABD"), r.calls(), "all contain 1AB; none start with it, so in order");
        r = d.partial("K1A", 10);
        assertEquals(List.of("K1ABC", "K1ABCD", "K1ABD"), r.calls());
        assertEquals(List.of("W1AW", "W1AWX"), d.partial("W1AW", 10).calls(), "the call itself is listed with the longer ones");
        assertEquals(List.of(), d.partial("K", 10).calls(), "one character is not enough to be useful");
    }

    @Test void partialLimitsTheListButReportsTheTotal() {
        ScpData.Result r = ScpData.parse(FILE).partial("1A", 2);
        assertEquals(2, r.calls().size());
        assertTrue(r.total() > 2);
        assertEquals(List.of("W1AW", "W1AWX"), ScpData.parse(FILE).partial("w1aw", 10).calls().subList(0, 2), "typed text is upper-cased");
    }

    @Test void nearFindsTheCallsOneKeystrokeAway() {
        ScpData d = ScpData.parse(FILE);
        assertTrue(d.near("K1ABE", 10).calls().containsAll(List.of("K1ABC", "K1ABD")), "wrong character");
        assertTrue(d.near("K1AB", 10).calls().contains("K1ABC"), "missing character");
        assertTrue(d.near("K1AABC", 10).calls().contains("K1ABC"), "extra character");
        assertTrue(d.near("K1BAC", 10).calls().contains("K1ABC"), "two swapped");
        assertFalse(d.near("K1ABC", 10).calls().contains("K1ABC"), "never the call itself");
        assertEquals(List.of(), d.near("ZZ9", 10).calls());
        assertEquals(List.of(), d.near("K1", 10).calls(), "too short to guess at");
    }

    @Test void oneOffIsExactlyOneEdit() {
        assertTrue(ScpData.oneOff("K1ABC", "K1ABD"));
        assertTrue(ScpData.oneOff("K1ABC", "K1AB"));
        assertTrue(ScpData.oneOff("K1AB", "K1ABC"));
        assertTrue(ScpData.oneOff("K1ABC", "K1BAC"));
        assertFalse(ScpData.oneOff("K1ABC", "K1ABC"));
        assertFalse(ScpData.oneOff("K1ABC", "K1ADE"), "two substitutions");
        assertFalse(ScpData.oneOff("K1ABC", "K1A"), "two deletions");
        assertFalse(ScpData.oneOff("K1ABC", "KAB1C"));
    }

    @Test void aPortableCallIsLookedUpByItsCore() {
        assertEquals("W1AW", ScpData.core("w1aw/4"));
        assertEquals("K1ABC", ScpData.core("OH/K1ABC"));
        assertEquals("K1ABC", ScpData.core("K1ABC/P"));
        assertEquals("K1ABC", ScpData.core(" k1abc "));
        assertEquals("", ScpData.core(null));
        assertTrue(ScpData.parse(FILE).partial("W1AW/4", 5).calls().contains("W1AW"));
    }
}
